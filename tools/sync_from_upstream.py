#!/usr/bin/env python3
"""Regenerate the Kiro plugin from the upstream Copilot plugin.

The Copilot port is used as the source because its skills and references are
already host-neutral ("prompt the user", "host shell or terminal capability").
This script applies the Kiro-specific transforms on top:

  * Agent Plugins 1.0.0 layout: plugin.json at the plugin root, and every skill
    self-contained with its own references/ folder (the spec does not guarantee
    that files outside skills/ survive installation, so the shared
    ../../references/ directory used upstream cannot be relied on).
  * ../../references/<file> -> references/<file>
  * Free Trial attribution ?source=copilot -> ?source=kiro
  * Copilot product names -> Kiro

README.md and LICENSE are Kiro-owned and never touched.

Usage:
  python3 tools/sync_from_upstream.py --upstream ../copilot-plugins
  python3 tools/sync_from_upstream.py --upstream ../copilot-plugins --check

--check regenerates into a temporary directory and exits 1 if the committed
plugin differs, so CI can detect drift from upstream.
"""

import argparse
import filecmp
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

PLUGIN = "42crunch-api-security-testing"
REPO_ROOT = Path(__file__).resolve().parent.parent
DEST = REPO_ROOT / "plugins" / PLUGIN

# Files generated by this script. Anything else in DEST is Kiro-owned.
GENERATED = ("plugin.json", "RECIPES.md", "skills")

TRANSFORMS = [
    (re.compile(r"\.\./\.\./references/"), "references/"),
    (re.compile(r"\?source=copilot\b"), "?source=kiro"),
    (re.compile(r"\bGitHub Copilot\b"), "Kiro"),
    (re.compile(r"\bCopilot\b"), "Kiro"),
]

# Host-specific vocabulary that must never reach the Kiro port. A hit means
# upstream introduced something the transforms above do not handle yet.
FORBIDDEN = [
    (re.compile(r"AskUserQuestion"), "Claude-only question tool"),
    (re.compile(r"`(Bash|Edit|Write|Read)` tool"), "Claude tool name"),
    (re.compile(r"\b(bash_tool|str_replace_editor|create_file)\b"), "claude.ai tool name"),
    (re.compile(r"CLAUDE_PLUGIN_ROOT|\$\{?PLUGIN_ROOT"), "host plugin-root variable"),
    (re.compile(r"\.\./\.\./references/"), "shared references path"),
    (re.compile(r"\?source=(claude|copilot|codex)\b"), "wrong Free Trial attribution"),
    (re.compile(r"\b(Copilot|Claude Code|Codex)\b"), "other host product name"),
    (re.compile(r"<scripts>"), "bundled-scripts placeholder (not yet ported)"),
]

# Kiro picks a power by its description and keywords, so both must name what the
# plugin covers. Without "graphql" the agent assumes OpenAPI only.
KIRO_DESCRIPTION = ("Audit OpenAPI specs and GraphQL schemas, scan running REST and GraphQL APIs "
                    "for vulnerabilities including BOLA/BFLA, and apply fixes with AI guardrails in Kiro.")
KIRO_KEYWORDS = ["42crunch", "42c-ast", "oas", "swagger", "graphql", "graphql-security", "rest-api",
                 "api-scan", "bola", "bfla", "sqg"]

SKILL_NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
MD_NAME_RE = re.compile(r"[A-Za-z0-9_-]+\.md")


def transform(text):
    for pattern, repl in TRANSFORMS:
        text = pattern.sub(repl, text)
    return text


def reference_closure(start_text, ref_dir):
    """Reference files reachable from start_text, following mentions transitively."""
    available = {p.name for p in ref_dir.glob("*.md")}
    seen, queue = set(), [start_text]
    while queue:
        for name in MD_NAME_RE.findall(queue.pop()):
            if name in available and name not in seen:
                seen.add(name)
                queue.append((ref_dir / name).read_text())
    return sorted(seen)


def build_plugin_json(src):
    up = json.loads((src / "plugin.json").read_text())
    keywords = list(up.get("keywords", []))
    keywords += [k for k in KIRO_KEYWORDS if k not in keywords]
    author = {k: v for k, v in up["author"].items() if k in ("name", "email", "url")}
    author.setdefault("url", "https://42crunch.com")
    return {
        "$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
        "name": PLUGIN,
        "version": up["version"],
        "description": KIRO_DESCRIPTION,
        "author": author,
        "homepage": "https://42crunch.com",
        "repository": "https://github.com/42Crunch-AI/kiro-plugins",
        "license": "MIT",
        "keywords": keywords,
    }


def generate(src, out):
    if (src / "scripts").exists():
        sys.exit(
            "upstream ships a scripts/ directory: bundled scripts and the <scripts> "
            "placeholder need a Kiro mapping before this script can sync them"
        )
    ref_dir = src / "references"
    out.mkdir(parents=True, exist_ok=True)

    (out / "plugin.json").write_text(json.dumps(build_plugin_json(src), indent=2) + "\n")
    (out / "RECIPES.md").write_text(transform((src / "RECIPES.md").read_text()))

    for skill_dir in sorted(p for p in (src / "skills").iterdir() if p.is_dir()):
        skill_md = (skill_dir / "SKILL.md").read_text()
        dest = out / "skills" / skill_dir.name
        dest.mkdir(parents=True)
        (dest / "SKILL.md").write_text(transform(skill_md))
        refs = reference_closure(skill_md, ref_dir)
        if refs:
            (dest / "references").mkdir()
            for name in refs:
                (dest / "references" / name).write_text(transform((ref_dir / name).read_text()))


def frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    fields, key = {}, None
    for line in m.group(1).splitlines():
        top = re.match(r"^([A-Za-z-]+):\s*(.*)$", line)
        if top:
            key = top.group(1)
            fields[key] = "" if top.group(2) in (">", "|", ">-", "|-") else top.group(2)
        elif key:
            fields[key] = (fields[key] + " " + line.strip()).strip()
    return fields


def lint(out):
    errors = []
    for path in sorted(out.rglob("*")):
        if not path.is_file() or path.suffix not in (".md", ".json"):
            continue
        rel = path.relative_to(out)
        for lineno, line in enumerate(path.read_text().splitlines(), 1):
            for pattern, why in FORBIDDEN:
                if pattern.search(line):
                    errors.append(f"{rel}:{lineno}: {why}: {line.strip()[:120]}")
    for skill_md in sorted(out.glob("skills/*/SKILL.md")):
        fm = frontmatter(skill_md.read_text())
        folder = skill_md.parent.name
        if fm.get("name") != folder:
            errors.append(f"{skill_md.relative_to(out)}: name {fm.get('name')!r} != folder {folder!r}")
        if not SKILL_NAME_RE.match(folder) or len(folder) > 64:
            errors.append(f"{skill_md.relative_to(out)}: invalid skill name {folder!r}")
        if not fm.get("description") or len(fm["description"]) > 1024:
            errors.append(f"{skill_md.relative_to(out)}: description missing or over 1024 chars")
    return errors


def dirs_differ(a, b):
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files:
        return True
    # dircmp compares shallowly; confirm byte equality of the common files.
    if any(not filecmp.cmp(a / f, b / f, shallow=False) for f in cmp.common_files):
        return True
    return any(dirs_differ(a / d, b / d) for d in cmp.common_dirs)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--upstream", required=True, type=Path,
                        help="path to a copilot-plugins checkout")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the committed plugin differs from a fresh sync")
    args = parser.parse_args()

    src = args.upstream.resolve() / "plugins" / PLUGIN
    if not (src / "plugin.json").exists():
        sys.exit(f"not an upstream plugin directory: {src}")

    with tempfile.TemporaryDirectory() as tmp:
        staged = Path(tmp) / PLUGIN
        generate(src, staged)
        errors = lint(staged)
        if errors:
            print("lint failed on generated plugin:", *errors, sep="\n  ", file=sys.stderr)
            return 1

        if args.check:
            stale = [n for n in GENERATED
                     if not (DEST / n).exists()
                     or ((staged / n).is_dir() and dirs_differ(staged / n, DEST / n))
                     or ((staged / n).is_file() and not filecmp.cmp(staged / n, DEST / n, shallow=False))]
            if stale:
                print("out of date with upstream:", ", ".join(stale), file=sys.stderr)
                return 1
            print("up to date with upstream")
            return 0

        DEST.mkdir(parents=True, exist_ok=True)
        for name in GENERATED:
            target = DEST / name
            if target.is_dir():
                shutil.rmtree(target)
            elif target.exists():
                target.unlink()
            if (staged / name).is_dir():
                shutil.copytree(staged / name, target)
            else:
                shutil.copy2(staged / name, target)

    version = json.loads((DEST / "plugin.json").read_text())["version"]
    print(f"synced {PLUGIN} {version} from {src}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
